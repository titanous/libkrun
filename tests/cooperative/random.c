/* Random bytes across a copy, for running threads with no debugger and no userfaultfd.
 *
 * Sixteen worker threads loop on one random source each: the getrandom system call, the vDSO
 * getrandom, a read of /dev/urandom and a read of /dev/random, each with 8, 32, 4096 and 1 MiB requests.
 * Before every call a thread fills its buffer with a pattern derived from the thread and sequence number,
 * then marks itself "in call". System calls are issued from inline assembly whose very next instruction
 * stores the return value ("commit"), so a thread found in the template "in call" with no commit had not
 * executed a single user instruction after the call when it froze.
 *
 * The host finds each thread's control page and the first and last page of its buffer in the template's
 * guest RAM by marker: a per-boot random nonce followed by a tag, placed at the start of the control page,
 * just before the buffer and just after it. (The production kernel has neither /proc/self/pagemap nor
 * /proc/sys, so the guest cannot report physical addresses.) It therefore knows, per thread, whether the
 * kernel had already generated bytes for the call in flight at the freeze.
 * After resume every copy keeps looping, records 16 more values, and writes all record rings to its own
 * disk for the host (tests/cooperative/random-run.py) to compare across copies.
 */
#define _GNU_SOURCE
#include <elf.h>
#include <errno.h>
#include <fcntl.h>
#include <pthread.h>
#include <sched.h>
#include <stdatomic.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/auxv.h>
#include <sys/mman.h>
#include <sys/mount.h>
#include <sys/reboot.h>
#include <sys/stat.h>
#include <sys/syscall.h>
#include <time.h>
#include <unistd.h>

#define THREADS 16
#define RING 65536
#define POST_RECORDS 16
#define PENDING (-9999L)
#define RING_MAGIC 0x31474e49524e4152ULL  /* "RANRING1" */
#define RING_OFFSET (1UL << 20)
#define RING_STRIDE (5UL << 20)
#define LEAD 64                           /* marker area before the buffer, in the same page */

enum kind { KIND_SYSCALL = 0, KIND_VDSO = 1, KIND_URANDOM = 2, KIND_RANDOM = 3 };
static const char *kind_names[] = { "getrandom", "vdso", "urandom", "random" };
static const size_t sizes[] = { 8, 32, 4096, 1 << 20 };

/* Read by the host from template RAM at offset 32 of the control page: keep in step with random-run.py. */
struct control {
    volatile uint64_t state;      /* 0 outside a call, 1 from the prefill until the record is written */
    volatile uint64_t seq;        /* sequence number of the current or last call */
    volatile int64_t commit;      /* PENDING until the instruction after the call stores the result */
    uint64_t kind, size;
    volatile uint64_t recorded;   /* last sequence number with a ring record */
};
struct record { uint64_t seq; int64_t ret; uint64_t hash; uint64_t head[2]; uint64_t tail[2]; uint64_t pad; };
_Static_assert(sizeof(struct record) == 64, "record layout");

struct worker {
    unsigned char *control_page;
    struct control *control;
    unsigned char *buffer;
    struct record *ring;
    void *vdso_state;
    unsigned long vdso_state_size;
    int fd;
    pthread_t thread;
};
static struct worker workers[THREADS];
static atomic_int resumed, parked, stop;
static unsigned char nonce[16];
typedef long (*vgetrandom_t)(void *, size_t, unsigned int, void *, size_t);
static vgetrandom_t vgetrandom;

static void fail(const char *what)
{
    printf("RANDCOPY FAIL %s errno=%d\n", what, errno);
    sync(); reboot(RB_POWER_OFF); for (;;) pause();
}

static uint64_t pattern(uint64_t thread, uint64_t seq, uint64_t word)
{
    return (seq * 0x9e3779b97f4a7c15ULL) ^ (word * 0xc2b2ae3d27d4eb4fULL) ^ (thread * 0x165667b19e3779f9ULL)
        ^ 0x5bd1e9955bd1e995ULL;
}

static uint64_t hash_words(const unsigned char *data, size_t length)
{
    uint64_t h = 0xcbf29ce484222325ULL, w;
    for (size_t i = 0; i < length; i += 8) {
        memcpy(&w, data + i, 8);
        h = (h ^ w) * 0x100000001b3ULL;
    }
    return h;
}

/* nonce, then tag word ('C' control, 'H' before buffer, 'T' after buffer, 'V' vDSO state page) with the
 * thread index, then the bitwise complement of the nonce's first word. */
static void mark(unsigned char *at, char tag, int thread)
{
    uint64_t word = ((uint64_t)(unsigned char)tag << 56) | (uint64_t)thread, check;
    memcpy(&check, nonce, 8); check = ~check;
    memcpy(at, nonce, 16); memcpy(at + 16, &word, 8); memcpy(at + 24, &check, 8);
}

/* The store into *commit is the first user instruction executed after the system call. */
static inline long syscall3_commit(long nr, long a, long b, long c, volatile int64_t *commit)
{
    long ret;
    asm volatile("syscall\n\tmovq %%rax, (%5)"
                 : "=a"(ret) : "0"(nr), "D"(a), "S"(b), "d"(c), "r"(commit) : "rcx", "r11", "memory");
    return ret;
}

static void *vdso_symbol(const char *name)
{
    const unsigned char *base = (const void *)getauxval(AT_SYSINFO_EHDR);
    if (!base) return NULL;
    const Elf64_Ehdr *eh = (const void *)base;
    const Elf64_Phdr *ph = (const void *)(base + eh->e_phoff);
    uintptr_t load = 0;
    const Elf64_Dyn *dyn = NULL;
    for (int i = 0; i < eh->e_phnum; i++) {
        if (ph[i].p_type == PT_LOAD && !load) load = (uintptr_t)base + ph[i].p_offset - ph[i].p_vaddr;
        if (ph[i].p_type == PT_DYNAMIC) dyn = (const void *)(base + ph[i].p_offset);
    }
    if (!dyn) return NULL;
    const Elf64_Sym *symbols = NULL; const char *strings = NULL; const Elf32_Word *hash = NULL;
    for (; dyn->d_tag != DT_NULL; dyn++) {
        if (dyn->d_tag == DT_SYMTAB) symbols = (const void *)(load + dyn->d_un.d_ptr);
        if (dyn->d_tag == DT_STRTAB) strings = (const void *)(load + dyn->d_un.d_ptr);
        if (dyn->d_tag == DT_HASH) hash = (const void *)(load + dyn->d_un.d_ptr);
    }
    if (!symbols || !strings || !hash) return NULL;
    for (Elf32_Word i = 0; i < hash[1]; i++)
        if (symbols[i].st_shndx != SHN_UNDEF && !strcmp(strings + symbols[i].st_name, name))
            return (void *)(load + symbols[i].st_value);
    return NULL;
}

static void *worker_loop(void *argument)
{
    struct worker *w = argument;
    struct control *c = w->control;
    uint64_t thread = (uint64_t)(w - workers);
    size_t n = c->size;
    int post = 0;
    for (uint64_t seq = 1;; seq++) {
        if (atomic_load(&resumed) && ++post > POST_RECORDS) break;
        c->commit = PENDING;
        for (size_t i = 0; i < n / 8; i++) ((uint64_t *)w->buffer)[i] = pattern(thread, seq, i);
        c->seq = seq;
        atomic_signal_fence(memory_order_seq_cst);
        c->state = 1;
        atomic_signal_fence(memory_order_seq_cst);
        long ret;
        switch (c->kind) {
        case KIND_SYSCALL:
            ret = syscall3_commit(SYS_getrandom, (long)w->buffer, (long)n, 0, &c->commit);
            break;
        case KIND_VDSO:
            ret = vgetrandom(w->buffer, n, 0, w->vdso_state, w->vdso_state_size);
            c->commit = ret;
            break;
        default:
            ret = syscall3_commit(SYS_read, w->fd, (long)w->buffer, (long)n, &c->commit);
            break;
        }
        atomic_signal_fence(memory_order_seq_cst);
        if (ret <= 0) fail("random call");
        struct record *r = &w->ring[seq % RING];
        r->seq = seq; r->ret = ret; r->hash = hash_words(w->buffer, n);
        memcpy(r->head, w->buffer, 16); memcpy(r->tail, w->buffer + n - 16, 16);
        c->recorded = seq;
        atomic_signal_fence(memory_order_seq_cst);
        c->state = 0;
    }
    atomic_fetch_add(&parked, 1);
    while (!atomic_load(&stop)) usleep(1000);
    return NULL;
}

static void *pages(size_t length)
{
    void *p = mmap(NULL, length, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_POPULATE, -1, 0);
    if (p == MAP_FAILED) fail("mmap");
    memset(p, 0, length);
    return p;
}

int main(void)
{
    mkdir("/dev", 0755); mkdir("/proc", 0755); mkdir("/sys", 0755);
    mount("devtmpfs", "/dev", "devtmpfs", 0, NULL); mount("proc", "/proc", "proc", 0, NULL);
    mount("sysfs", "/sys", "sysfs", 0, NULL);
    int console = open("/dev/ttyS0", O_RDWR);
    if (console >= 0) { dup2(console, 0); dup2(console, 1); dup2(console, 2); }
    setbuf(stdout, NULL);
    if (syscall(SYS_getrandom, nonce, sizeof(nonce), 0) != sizeof(nonce)) fail("nonce");
    vgetrandom = (vgetrandom_t)vdso_symbol("__vdso_getrandom");
    struct { uint32_t size, prot, flags, reserved[13]; } params;
    if (!vgetrandom || vgetrandom(NULL, 0, 0, &params, ~0UL)) fail("vDSO getrandom unavailable");
    int disk = open("/dev/vda", O_RDWR);
    if (disk < 0) fail("disk");
    for (int i = 0; i < THREADS; i++) {
        struct worker *w = &workers[i];
        w->control_page = pages(4096);
        mark(w->control_page, 'C', i);
        w->control = (struct control *)(w->control_page + 32);
        w->control->kind = i / 4; w->control->size = sizes[i % 4];
        size_t n = w->control->size;
        unsigned char *region = pages((LEAD + n + 32 + 4095) / 4096 * 4096);
        mark(region, 'H', i);
        w->buffer = region + LEAD;
        mark(w->buffer + n, 'T', i);
        w->ring = pages(sizeof(struct record) * RING);
        w->fd = -1;
        if (w->control->kind == KIND_URANDOM || w->control->kind == KIND_RANDOM) {
            w->fd = open(w->control->kind == KIND_URANDOM ? "/dev/urandom" : "/dev/random", O_RDONLY);
            if (w->fd < 0) fail("random device");
        }
        if (w->control->kind == KIND_VDSO) {
            if (params.size > 2048) fail("vDSO state size");
            w->vdso_state_size = params.size;
            w->vdso_state = mmap(NULL, 4096, params.prot, params.flags, -1, 0);
            if (w->vdso_state == MAP_FAILED) fail("vDSO state");
            mark((unsigned char *)w->vdso_state + 2048, 'V', i);
        }
    }
    if (mlockall(MCL_CURRENT | MCL_FUTURE)) fail("mlockall");
    /* Workers inherit normal scheduling; the real-time main thread runs as soon as a copy thaws, so the
     * workers stop well before their record rings wrap past the freeze point. */
    struct sched_param realtime = { .sched_priority = 10 };
    pthread_attr_t normal;
    struct sched_param other = { .sched_priority = 0 };
    if (pthread_attr_init(&normal) || pthread_attr_setinheritsched(&normal, PTHREAD_EXPLICIT_SCHED) ||
        pthread_attr_setschedpolicy(&normal, SCHED_OTHER) || pthread_attr_setschedparam(&normal, &other))
        fail("worker attributes");
    if ((errno = pthread_setschedparam(pthread_self(), SCHED_FIFO, &realtime))) fail("real-time main thread");
    printf("RANDCOPY NONCE ");
    for (unsigned i = 0; i < sizeof(nonce); i++) printf("%02x", nonce[i]);
    printf("\n");
    for (int i = 0; i < THREADS; i++)
        if (pthread_create(&workers[i].thread, &normal, worker_loop, &workers[i])) fail("pthread");
    for (int i = 0; i < THREADS; i++)
        while (workers[i].control->recorded < 3) usleep(1000);
    /* Spread the freeze over the workers' loop phases. */
    unsigned int jitter;
    if (syscall(SYS_getrandom, &jitter, sizeof(jitter), 0) != sizeof(jitter)) fail("jitter");
    usleep(jitter % 5000);
    int freeze = open("/sys/power/nitro_freeze", O_WRONLY);
    if (freeze < 0) fail("trigger open");
    printf("RANDCOPY FREEZE cpus=%ld threads=%d\n", sysconf(_SC_NPROCESSORS_ONLN), THREADS);
    if (write(freeze, "1", 1) != 1) fail("freeze");
    /* Only copies get here. */
    atomic_store(&resumed, 1);
    for (int waited = 0; atomic_load(&parked) < THREADS; waited++) {
        if (waited > 20000) fail("workers did not record after resume");
        usleep(1000);
    }
    for (int i = 0; i < THREADS; i++) {
        uint64_t header[4] = { RING_MAGIC, (uint64_t)i, workers[i].control->recorded, RING };
        off_t at = RING_OFFSET + (off_t)i * RING_STRIDE;
        if (pwrite(disk, header, sizeof(header), at) != sizeof(header) ||
            pwrite(disk, workers[i].ring, sizeof(struct record) * RING, at + 4096) != (ssize_t)(sizeof(struct record) * RING))
            fail("ring write");
    }
    if (fsync(disk)) fail("ring sync");
    atomic_store(&stop, 1);
    printf("RANDCOPY DONE cpus=%ld\n", sysconf(_SC_NPROCESSORS_ONLN));
    for (int i = 0; i < THREADS; i++) printf("RANDCOPY THREAD %d %s %zu last=%llu\n", i,
        kind_names[workers[i].control->kind], (size_t)workers[i].control->size,
        (unsigned long long)workers[i].control->recorded);
    reboot(RB_POWER_OFF); for (;;) pause();
}
