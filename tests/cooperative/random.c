/* Random bytes across a copy, for running threads with no debugger and no userfaultfd.
 *
 * Sixteen worker threads loop on one random source each: the getrandom system call, the vDSO
 * getrandom, a read of /dev/urandom and a read of /dev/random, each with 8, 32, 4096 and 1 MiB requests.
 * Before every call a thread fills its buffer with a pattern derived from the thread and sequence number,
 * then marks itself "in call". System calls are issued from inline assembly whose very next instruction
 * stores the return value ("commit"), so a thread found in the template "in call" with no commit had not
 * executed a single user instruction after the call when it froze.
 *
 * The host finds each thread's control page and the first and last page of its buffer in the template's
 * guest RAM by marker: a per-boot random nonce followed by a tag, placed at the start of the control page,
 * just before the buffer and just after it. (The production kernel has neither /proc/self/pagemap nor
 * /proc/sys, so the guest cannot report physical addresses.) It therefore knows, per thread, whether the
 * kernel had already generated bytes for the call in flight at the freeze.
 * After resume every copy keeps looping, records 16 more values, and writes all record rings to its own
 * disk for the host (tests/cooperative/random-run.py) to compare across copies.
 *
 * Tasks that read random bytes and EXIT before or during the freeze, as in every real guest: before each
 * freeze the guest runs an ordinary shell loop of 300 short processes (when /bin/busybox is present),
 * 100 processes that exec this binary, 50 forked processes and 100 threads that each read random bytes
 * through getrandom, /dev/urandom and /dev/random and exit; it leaves 8 such children unreaped (zombies)
 * and keeps a churn thread creating short-lived reading threads and processes through the freeze. A copy
 * must thaw and reap them all ("RANDCOPY CHURN ... ok").
 */
