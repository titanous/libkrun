/// Success exit code.
pub const FC_EXIT_CODE_OK: u8 = 0;
/// Generic error exit code.
pub const FC_EXIT_CODE_GENERIC_ERROR: u8 = 1;
/// Generic exit code for an error considered not possible to occur if the program logic is sound.
pub const FC_EXIT_CODE_UNEXPECTED_ERROR: u8 = 2;
/// Guest requested a reboot (KVM_SYSTEM_EVENT_RESET).
pub const FC_EXIT_CODE_REBOOT: u8 = 3;
/// Firecracker was shut down after intercepting a restricted system call.
pub const FC_EXIT_CODE_BAD_SYSCALL: u8 = 148;
/// Firecracker was shut down after intercepting `SIGBUS`.
pub const FC_EXIT_CODE_SIGBUS: u8 = 149;
/// Firecracker was shut down after intercepting `SIGSEGV`.
pub const FC_EXIT_CODE_SIGSEGV: u8 = 150;
/// Bad configuration for microvm's resources, when using a single json.
pub const FC_EXIT_CODE_BAD_CONFIGURATION: u8 = 152;
/// Command line arguments parsing error.
pub const FC_EXIT_CODE_ARG_PARSING: u8 = 153;

/// Errors associated with the VMM internal logic. These errors cannot be generated by direct user
/// input, but can result from bad configuration of the host (for example if Firecracker doesn't
/// have permissions to open the KVM fd).
#[derive(Debug)]
pub enum Error {
    /// This error is thrown by the minimal boot loader implementation.
    ConfigureSystem(arch::Error),
    /// Legacy devices work with Event file descriptors and the creation can fail because
    /// of resource exhaustion.
    #[cfg(target_arch = "x86_64")]
    CreateLegacyDevice(device_manager::legacy::Error),
    /// The VM has no generation identifier device.
    VmGenerationUnavailable,
    /// Cannot update the generation identifier in guest memory.
    VmGenerationMemory(vm_memory::GuestMemoryError),
    /// Cannot read from an Event file descriptor.
    EventFd(io::Error),
    /// Polly error wrapper.
    EventManager(event_manager::Error),
    /// I8042 Error.
    I8042Error(devices::legacy::I8042DeviceError),
    /// Cannot access kernel file.
    KernelFile(io::Error),
    /// Cannot open /dev/kvm. Either the host does not have KVM or Firecracker does not have
    /// permission to open the file descriptor.
    KvmContext(vstate::Error),
    #[cfg(target_arch = "x86_64")]
    /// Cannot add devices to the Legacy I/O Bus.
    LegacyIOBus(device_manager::legacy::Error),
    /// Cannot load command line.
    LoadCommandline(kernel::cmdline::Error),
    /// Cannot add a device to the MMIO Bus.
    RegisterMMIODevice(device_manager::mmio::Error),
    /// Write to the serial console failed.
    Serial(io::Error),
    #[cfg(any(target_arch = "aarch64", target_arch = "riscv64"))]
    /// Cannot generate or write FDT
    SetupFDT(devices::fdt::Error),
    /// Cannot create Timer file descriptor.
    TimerFd(io::Error),
    /// Vcpu error.
    Vcpu(vstate::Error),
    /// Cannot send event to vCPU.
    VcpuEvent(vstate::Error),
    /// Cannot create a vCPU handle.
    VcpuHandle(vstate::Error),
    /// vCPU pause failed.
    VcpuPause,
    /// vCPU resume failed.
    VcpuResume,
    /// Cannot spawn a new Vcpu thread.
    VcpuSpawn(std::io::Error),
    /// Vm error.
    Vm(vstate::Error),
    /// Error thrown by observer object on Vmm initialization.
    VmmObserverInit(utils::errno::Error),
    /// Error thrown by observer object on Vmm teardown.
    VmmObserverTeardown(utils::errno::Error),
}

impl Display for Error {
    fn fmt(&self, f: &mut Formatter) -> std::fmt::Result {
        use self::Error::*;

        match self {
            ConfigureSystem(e) => write!(f, "System configuration error: {e:?}"),
            #[cfg(target_arch = "x86_64")]
            CreateLegacyDevice(e) => write!(f, "Error creating legacy device: {e:?}"),
            VmGenerationUnavailable => write!(f, "VM generation identifier unavailable"),
            VmGenerationMemory(e) => write!(f, "Cannot update VM generation identifier: {e}"),
            EventFd(e) => write!(f, "Event fd error: {e}"),
            EventManager(e) => write!(f, "Event manager error: {e:?}"),
            I8042Error(e) => write!(f, "I8042 error: {e}"),
            KernelFile(e) => write!(f, "Cannot access kernel file: {e}"),
            KvmContext(e) => write!(f, "Failed to validate KVM support: {e:?}"),
            #[cfg(target_arch = "x86_64")]
            LegacyIOBus(e) => write!(f, "Cannot add devices to the legacy I/O Bus. {e}"),
            LoadCommandline(e) => write!(f, "Cannot load command line: {e}"),
            RegisterMMIODevice(e) => write!(f, "Cannot add a device to the MMIO Bus. {e}"),
            Serial(e) => write!(f, "Error writing to the serial console: {e:?}"),
            #[cfg(any(target_arch = "aarch64", target_arch = "riscv64"))]
            SetupFDT(e) => write!(f, "Error generating or writing FDT: {e:?}"),
            TimerFd(e) => write!(f, "Error creating timer fd: {e}"),
            Vcpu(e) => write!(f, "Vcpu error: {e}"),
            VcpuEvent(e) => write!(f, "Cannot send event to vCPU. {e:?}"),
            VcpuHandle(e) => write!(f, "Cannot create a vCPU handle. {e}"),
            VcpuPause => write!(f, "vCPUs pause failed."),
            VcpuResume => write!(f, "vCPUs resume failed."),
            VcpuSpawn(e) => write!(f, "Cannot spawn Vcpu thread: {e}"),
            Vm(e) => write!(f, "Vm error: {e}"),
            VmmObserverInit(e) => write!(
                f,
                "Error thrown by observer object on Vmm initialization: {e}"
            ),
            VmmObserverTeardown(e) => {
                write!(f, "Error thrown by observer object on Vmm teardown: {e}")
            }
        }
    }
}

/// Trait for objects that need custom initialization and teardown during the Vmm lifetime.
pub trait VmmEventsObserver {
    /// This function will be called during microVm boot.
    fn on_vmm_boot(&mut self) -> std::result::Result<(), utils::errno::Error> {
        Ok(())
    }
    /// This function will be called on microVm teardown.
    fn on_vmm_stop(&mut self) -> std::result::Result<(), utils::errno::Error> {
        Ok(())
    }
}

/// Shorthand result type for internal VMM commands.
pub type Result<T> = std::result::Result<T, Error>;

/// Contains the state and associated methods required for the Firecracker VMM.
pub struct Vmm {
    // Guest VM core resources.
    guest_memory: GuestMemoryMmap,
    arch_memory_info: ArchMemoryInfo,

    kernel_cmdline: KernelCmdline,

    vcpus_handles: Vec<VcpuHandle>,
    exit_evt: EventFd,
    vm: Vm,
    exit_observers: Vec<Arc<Mutex<dyn VmmExitObserver>>>,
    exit_code: Arc<AtomicI32>,
    vm_exit: crate::vm_exit::SharedVmExit,
    vcpu_exit_flag: Arc<AtomicBool>,

    // Guest VM devices.
    mmio_device_manager: MMIODeviceManager,
    #[cfg(target_arch = "x86_64")]
    pio_device_manager: PortIODeviceManager,

    // Balloon device reference for API access.
    #[cfg(not(feature = "tee"))]
    pub(crate) balloon: Option<std::sync::Arc<std::sync::Mutex<devices::virtio::balloon::Balloon>>>,

    // VMGENID device for VM generation tracking (x86_64 and aarch64).
    #[cfg(any(target_arch = "x86_64", target_arch = "aarch64"))]
    pub(crate) vmgenid: Option<devices::vmgenid::Vmgenid>,
}

impl Vmm {
    /// Write a fresh generation identifier and notify the running guest.
    /// The guest driver reseeds its random pool when it handles this interrupt.
    #[cfg(any(target_arch = "x86_64", target_arch = "aarch64"))]
    pub fn notify_vm_generation_change(&mut self) -> Result<[u8; 16]> {
        let device = self
            .vmgenid
            .as_mut()
            .ok_or(Error::VmGenerationUnavailable)?;
        let (_, new_id) = device
            .update_guid(&self.guest_memory)
            .map_err(Error::VmGenerationMemory)?;
        device.signal_interrupt().map_err(Error::EventFd)?;
        Ok(new_id)
    }

    /// Gets the balloon device reference if available.
    #[cfg(not(feature = "tee"))]
    pub fn get_balloon(
        &self,
    ) -> Option<&std::sync::Arc<std::sync::Mutex<devices::virtio::balloon::Balloon>>> {
        self.balloon.as_ref()
    }

    /// Gets the the specified bus device.
    pub fn get_bus_device(
        &self,
        device_type: DeviceType,
        device_id: &str,
    ) -> Option<&Mutex<dyn BusDevice>> {
        self.mmio_device_manager.get_device(device_type, device_id)
    }

    /// Starts the microVM vcpus.
    pub fn start_vcpus(&mut self, mut vcpus: Vec<Vcpu>) -> Result<()> {
        self.start_vcpus_paused(&mut vcpus)?;

        // The vcpus start off in the `Paused` state, let them run.
        self.resume_vcpus()?;

        Ok(())
    }

    /// Starts the microVM vcpus without resuming them.
    ///
    /// After this call vCPU threads wait in their initial event loop for Resume.
    pub fn start_vcpus_paused(&mut self, vcpus: &mut Vec<Vcpu>) -> Result<()> {
        Vcpu::register_kick_signal_handler();

        self.vcpus_handles.reserve(vcpus.len());

        for vcpu in vcpus.drain(..) {
            let mut vcpu = vcpu;
            vcpu.set_mmio_bus(self.mmio_device_manager.bus.clone());

            self.vcpus_handles
                .push(vcpu.start_threaded().map_err(Error::VcpuHandle)?);
        }

        Ok(())
    }

    /// Sends a pause command to all vcpus and waits for confirmation.
    pub fn pause_vcpus(&mut self) -> Result<()> {
        for handle in self.vcpus_handles.iter() {
            handle
                .send_event(VcpuEvent::Pause)
                .map_err(Error::VcpuEvent)?;
        }
        for handle in self.vcpus_handles.iter() {
            match handle
                .response_receiver()
                .recv_timeout(Duration::from_millis(1000))
            {
                Ok(VcpuResponse::Paused) => (),
                _ => return Err(Error::VcpuPause),
            }
        }
        Ok(())
    }

    /// Sends a resume command to the vcpus.
    pub fn resume_vcpus(&mut self) -> Result<()> {
        for handle in self.vcpus_handles.iter() {
            handle
                .send_event(VcpuEvent::Resume)
                .map_err(Error::VcpuEvent)?;
        }
        for handle in self.vcpus_handles.iter() {
            match handle
                .response_receiver()
                .recv_timeout(Duration::from_millis(1000))
            {
                Ok(VcpuResponse::Resumed) => (),
                _ => return Err(Error::VcpuResume),
            }
        }
        Ok(())
    }

    /// Configures the system for boot.
    pub fn configure_system(
        &self,
        vcpus: &[Vcpu],
        _intc: &IrqChip,
        initrd: &Option<InitrdConfig>,
        _smbios_oem_strings: &Option<Vec<String>>,
    ) -> Result<()> {
        #[cfg(target_arch = "x86_64")]
        {
            let cmdline_len = if cfg!(feature = "tee") {
                arch::x86_64::layout::CMDLINE_SEV_SIZE
            } else {
                self.kernel_cmdline.len() + 1
            };

            arch::x86_64::configure_system(
                &self.guest_memory,
                &self.arch_memory_info,
                vm_memory::GuestAddress(arch::x86_64::layout::CMDLINE_START),
                cmdline_len,
                initrd,
                vcpus.len() as u8,
            )
            .map_err(Error::ConfigureSystem)?;
        }

        #[cfg(target_arch = "aarch64")]
        {
            let vcpu_mpidr = vcpus.iter().map(|cpu| cpu.get_mpidr()).collect();
            fdt::create_fdt(
                &self.guest_memory,
                &self.arch_memory_info,
                vcpu_mpidr,
                self.kernel_cmdline.as_str(),
                self.mmio_device_manager.get_device_info(),
                _intc,
                initrd,
            )
            .map_err(Error::SetupFDT)?;
        }

        #[cfg(target_arch = "aarch64")]
        {
            arch::aarch64::configure_system(
                &self.guest_memory,
                &self.arch_memory_info,
                _smbios_oem_strings,
            )
            .map_err(Error::ConfigureSystem)?;
        }

        #[cfg(target_arch = "riscv64")]
        {
            fdt::create_fdt(
                &self.guest_memory,
                &self.arch_memory_info,
                vcpus.len() as u32,
                self.kernel_cmdline.as_str(),
                self.mmio_device_manager.get_device_info(),
                _intc,
                initrd,
            )
            .map_err(Error::SetupFDT)?;

            arch::riscv64::configure_system(&self.guest_memory, _smbios_oem_strings)
                .map_err(Error::ConfigureSystem)?;
        }

        Ok(())
    }

    /// Returns a reference to the guest memory.
    pub fn guest_memory(&self) -> &GuestMemoryMmap {
        &self.guest_memory
    }

    /// Returns a reference to the arch memory info.
    pub fn arch_memory_info(&self) -> &ArchMemoryInfo {
        &self.arch_memory_info
    }

    /// Injects CTRL+ALT+DEL keystroke combo in the i8042 device.
    #[cfg(target_arch = "x86_64")]
    pub fn send_ctrl_alt_del(&mut self) -> Result<()> {
        self.pio_device_manager
            .i8042
            .lock()
            .expect("i8042 lock was poisoned")
            .trigger_ctrl_alt_del()
            .map_err(Error::I8042Error)
    }

    /// Registers an exit observer that will be called when the VM exits.
    pub fn register_exit_observer(&mut self, observer: Arc<Mutex<dyn VmmExitObserver>>) {
        self.exit_observers.push(observer);
    }

    /// Waits for all vCPUs to exit and stores exit information in shared state.
    pub fn stop(&mut self, vm_exit: crate::vm_exit::VmExit) {
        info!("Vmm is stopping: {vm_exit:?}");

        // Stop and join vCPUs before observers inspect the final guest rings.
        self.vcpu_exit_flag.store(true, Ordering::Release);
        for handle in &mut self.vcpus_handles {
            handle.request_shutdown();
        }
        let deadline = std::time::Instant::now() + Duration::from_secs(2);
        let mut joined = true;
        for handle in &mut self.vcpus_handles {
            joined &= handle.join_until(deadline);
        }
        let later_code = aggregate_vcpu_exits(self.vcpus_handles.iter().flat_map(|handle| {
            handle
                .response_receiver()
                .try_iter()
                .filter_map(|response| match response {
                    VcpuResponse::Exited(code) => Some(code),
                    _ => None,
                })
        }));
        let vm_exit = if !joined || later_code == FC_EXIT_CODE_GENERIC_ERROR {
            crate::vm_exit::VmExit::Error {
                message: "vCPU failed or missed stop join deadline".into(),
            }
        } else {
            vm_exit
        };
        self.vcpus_handles.clear();
        #[cfg(target_arch = "x86_64")]
        let vm_exit = crate::vm_exit::VmExit::resolve(
            vm_exit,
            match self.exit_code.load(Ordering::Acquire) {
                i32::MAX => None,
                code => Some(code),
            },
            self.pio_device_manager
                .stop_reason
                .0
                .load(Ordering::Acquire),
        );

        // A detached CPU may still access rings: final drain is unsafe in that case.
        for observer in &self.exit_observers {
            let mut observer = observer.lock().expect("Poisoned mutex for exit observer");
            if joined {
                observer.on_vmm_exit();
            } else {
                observer.on_vmm_exit_with_running_cpu();
            }
        }

        // Store the exit reason for Context::run() to read
        *self.vm_exit.lock().expect("Poisoned vm_exit lock") = Some(vm_exit);
    }

    /// Returns a reference to the inner KVM Vm object.
    pub fn kvm_vm(&self) -> &Vm {
        &self.vm
    }
}

impl Subscriber for Vmm {
    /// Handle a read event (EPOLLIN).
    fn process(&mut self, event: &EpollEvent, _: &mut EventManager) {
        let source = event.fd();
        let event_set = event.event_set();

        if source == self.exit_evt.as_raw_fd() && event_set == EventSet::IN {
            debug!("Vmm: exit_evt fired, shutting down");
            let _ = self.exit_evt.read();

            let vcpu_exit_code =
                aggregate_vcpu_exits(self.vcpus_handles.iter().flat_map(|handle| {
                    handle
                        .response_receiver()
                        .try_iter()
                        .filter_map(|response| match response {
                            VcpuResponse::Exited(code) => Some(code),
                            _ => None,
                        })
                }));

            let vmm_exit_code = self.exit_code.load(Ordering::SeqCst);

            // Log which exit code is being used for shutdown
            if vmm_exit_code != i32::MAX {
                debug!("using vmm exit code: {vmm_exit_code}");
            } else {
                debug!("using vcpu exit code: {vcpu_exit_code}");
            }

            let vm_exit = resolve_vm_exit(vcpu_exit_code, vmm_exit_code);
            self.stop(vm_exit);
        } else {
            error!("Spurious EventManager event for handler: Vmm");
        }
    }

    fn interest_list(&self) -> Vec<EpollEvent> {
        vec![EpollEvent::new(
            EventSet::IN,
            self.exit_evt.as_raw_fd() as u64,
        )]
    }
}

fn aggregate_vcpu_exits(codes: impl IntoIterator<Item = u8>) -> u8 {
    codes.into_iter().fold(FC_EXIT_CODE_OK, |old, code| {
        if old == FC_EXIT_CODE_GENERIC_ERROR || code == FC_EXIT_CODE_GENERIC_ERROR {
            FC_EXIT_CODE_GENERIC_ERROR
        } else if code != FC_EXIT_CODE_OK {
            code
        } else {
            old
        }
    })
}

/// Helper function to resolve VmExit variant from exit codes.
/// This is the core logic used by Subscriber::process() to determine
/// the correct VmExit variant based on vCPU exit code and VMM exit code.
/// Tests call this same function to verify the dispatch logic.
pub(crate) fn resolve_vm_exit(vcpu_exit_code: u8, vmm_exit_code: i32) -> crate::vm_exit::VmExit {
    let terminal = if vcpu_exit_code == FC_EXIT_CODE_GENERIC_ERROR {
        crate::vm_exit::VmExit::Error {
            message: "vCPU fatal error".into(),
        }
    } else {
        // Reset, PSCI events and terminal faults do not establish guest intent.
        crate::vm_exit::VmExit::Fault
    };
    crate::vm_exit::VmExit::resolve(
        terminal,
        (vmm_exit_code != i32::MAX).then_some(vmm_exit_code),
        0,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn later_cpu_error_wins() {
        assert_eq!(
            aggregate_vcpu_exits([FC_EXIT_CODE_OK, FC_EXIT_CODE_GENERIC_ERROR]),
            FC_EXIT_CODE_GENERIC_ERROR
        );
        assert_eq!(
            aggregate_vcpu_exits([FC_EXIT_CODE_GENERIC_ERROR, FC_EXIT_CODE_OK]),
            FC_EXIT_CODE_GENERIC_ERROR
        );
    }

    /// Test VM exit enum variants and derives
    #[test]
    fn test_vm_exit_enum() {
        // Test Shutdown variant construction and clone
        let exit_shutdown = crate::vm_exit::VmExit::Shutdown { exit_code: 0 };
        let exit_shutdown_cloned = exit_shutdown.clone();
        assert_eq!(exit_shutdown, exit_shutdown_cloned);

        // Test different exit codes
        let exit_42 = crate::vm_exit::VmExit::Shutdown { exit_code: 42 };
        assert_ne!(exit_shutdown, exit_42);

        // Test RebootRequested variant
        let exit_reboot = crate::vm_exit::VmExit::RebootRequested;
        let exit_reboot_cloned = exit_reboot.clone();
        assert_eq!(exit_reboot, exit_reboot_cloned);

        // Test Error variant
        let exit_error = crate::vm_exit::VmExit::Error {
            message: "test error".into(),
        };
        let exit_error_cloned = exit_error.clone();
        assert_eq!(exit_error, exit_error_cloned);

        // Test Debug trait
        let debug_str = format!("{:?}", exit_shutdown);
        assert!(debug_str.contains("Shutdown"));
    }

    /// Test vm-exit.AC1.1: Normal guest shutdown (HLT) returns Shutdown { exit_code: 0 }
    #[test]
    fn test_shutdown_with_zero_exit_code() {
        let vm_exit = resolve_vm_exit(FC_EXIT_CODE_OK, i32::MAX);
        assert_eq!(vm_exit, crate::vm_exit::VmExit::Fault);
    }

    /// Test vm-exit.AC1.2: Guest-set exit code is returned in Shutdown variant
    #[test]
    fn test_shutdown_with_guest_exit_code() {
        // Guest set exit code via vmm_exit_code (virtio-fs ioctl)
        let vm_exit = resolve_vm_exit(FC_EXIT_CODE_OK, 42);
        assert_eq!(vm_exit, crate::vm_exit::VmExit::Shutdown { exit_code: 42 });
    }

    /// Test vm-exit.AC1.3: KVM_SYSTEM_EVENT_RESET returns RebootRequested
    #[test]
    fn test_reboot_requested() {
        let vm_exit = resolve_vm_exit(FC_EXIT_CODE_REBOOT, i32::MAX);
        assert_eq!(vm_exit, crate::vm_exit::VmExit::Fault);
    }

    /// Test vm-exit.AC2.1: vCPU fatal errors return Error variant
    #[test]
    fn test_vcpu_fatal_error() {
        let vm_exit = resolve_vm_exit(FC_EXIT_CODE_GENERIC_ERROR, i32::MAX);
        match vm_exit {
            crate::vm_exit::VmExit::Error { ref message } => {
                assert_eq!(message, "vCPU fatal error");
            }
            _ => panic!("Expected Error variant"),
        }
    }

    /// Test shared exit state storage contract
    #[test]
    fn test_shared_vm_exit_storage() {
        let vm_exit: crate::vm_exit::SharedVmExit = Arc::new(Mutex::new(None));

        // Initially should be None
        {
            let guard = vm_exit.lock().expect("Poisoned lock");
            assert!(guard.is_none());
        }

        // Store a VmExit value
        {
            let mut guard = vm_exit.lock().expect("Poisoned lock");
            *guard = Some(crate::vm_exit::VmExit::Shutdown { exit_code: 0 });
        }

        // Verify it was stored
        {
            let guard = vm_exit.lock().expect("Poisoned lock");
            assert_eq!(
                *guard,
                Some(crate::vm_exit::VmExit::Shutdown { exit_code: 0 })
            );
        }
    }
}
